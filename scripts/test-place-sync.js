const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const vm = require("node:vm");
const { searchPlaces } = require("../lib/placeSearch");

const directory = fs.mkdtempSync(path.join(os.tmpdir(), "navigation-place-test-"));
process.env.NAV_DATA_DIR = directory;
const { createPlace } = require("../lib/catalogStore");
const { updatePlaceStatus, readPlaces, deletePlaceRecord } = require("../lib/placeStore");
try {
  const place = { id: "test-shop", mapId: "test-map", floorId: "f1", name: "Tea House", x: 87, y: 43, keywords: "milk tea", description: "near elevator" };
  createPlace(place);
  updatePlaceStatus(place.id, "closed", "Mon-Fri 10:00-22:00");
  createPlace({ ...place, description: "beside elevator" });
  const saved = readPlaces().find(item => item.id === place.id);
  assert.equal(saved.businessStatus, "closed");
  assert.equal(saved.openingHours, "Mon-Fri 10:00-22:00");
  assert.equal(saved.x, 87);
  const builtin = readPlaces().find(item => item.id === "k-area-k11");
  assert.ok(builtin);
  createPlace({ ...builtin, name: "Edited built-in" });
  deletePlaceRecord({ placeId: builtin.id });
  assert.ok(!readPlaces().some(item => item.id === builtin.id), "Deleted override must not reveal built-in");
  const tombstones = JSON.parse(fs.readFileSync(path.join(directory, "place_overrides.json"), "utf8"));
  assert.equal(tombstones[builtin.id].deleted, true);
  const other = { id: "other", name: "Tea", keywords: "", description: "" };
  assert.equal(searchPlaces([other, saved], "milk tea")[0].id, place.id);
  assert.equal(searchPlaces([saved], "elevator").length, 1);
  assert.equal(searchPlaces([saved], "電梯").length, 0);
  assert.equal(searchPlaces([{ name: "服務台", description: "中央廣場" }], "中廣").length, 1);

  const source = fs.readFileSync(path.join(__dirname, "../server.js"), "utf8");
  const start = source.indexOf("function fingerprintRecencyWeight(");
  const end = source.indexOf("function rankKnnProfiles(", start);
  const context = vm.createContext({ Date, Math, Number });
  vm.runInContext(source.slice(start, end), context);
  const weight = context.fingerprintRecencyWeight;
  assert.ok(weight({ scannedAt: new Date().toISOString() }) > weight({ scannedAt: new Date(Date.now() - 90 * 86400000).toISOString() }));
  assert.equal(weight({ scannedAt: "invalid" }), 0.25);
  assert.ok(weight({ scannedAt: "2099-01-01" }) <= 1);
  const admin = fs.readFileSync(path.join(__dirname, "../public/admin.html"), "utf8");
  for (const match of admin.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)) new vm.Script(match[1]);
  assert(admin.includes('id="newPlaceCategoryOptions"'), "admin needs independent category checkboxes");
  assert(admin.includes('input[type="checkbox"]:checked'), "admin must preserve all checked categories");
  assert(!admin.includes('id="newPlaceCategory" multiple'), "native multiple select is not an acceptable category picker");
  const initBlock = admin.slice(admin.indexOf("async function init()"), admin.indexOf("function sortMapsForAdmin"));
  assert(!initBlock.includes('await loadStorageStatus();'), "slow storage status must not block the map dashboard");
  assert(!initBlock.includes('loadStorageStatus().catch'), "storage status must start after primary map data is visible");
  const dashboardBlock = admin.slice(admin.indexOf("async function loadDashboard()"), admin.indexOf("async function loadSupplementalDashboard"));
  assert(dashboardBlock.indexOf('loadStorageStatus().catch') > dashboardBlock.indexOf('地圖與點位已載入'), "storage status must be deferred until after primary rendering");
  assert(admin.includes("loadSupplementalDashboard(mapId, floorId, loadVersion)"), "slow management panels must load after primary map data");
  assert(admin.includes("Promise.allSettled(["), "supplemental panel failures must be isolated");
  const collectorActivity = fs.readFileSync(path.join(__dirname, "../android/IndoorNavigation/app/src/main/java/com/example/wififingerprintcollector/MainActivity.kt"), "utf8");
  const layout = fs.readFileSync(path.join(__dirname, "../android/IndoorNavigation/app/src/main/res/layout/activity_main.xml"), "utf8");
  const apMenu = collectorActivity.slice(collectorActivity.indexOf("private fun showApCalibrationMenu()"), collectorActivity.indexOf("private fun buildApCalibrationCandidates()"));
  assert(apMenu.includes('"1. 找候選基地台"'), "collector AP survey menu must expose candidate generation");
  assert(apMenu.includes('"2. 選擇基地台並開始測量"'), "collector AP survey menu must expose guided measurement");
  assert(!apMenu.includes(".setMessage("), "Android list dialogs must not replace the AP calibration choices with a message");
  assert(collectorActivity.includes("captureApSurveyMeasurement(x, y)"), "collector must capture temporary AP survey points from the map");
  assert(collectorActivity.includes("撤銷上一個橘色臨時點"), "collector must allow the latest temporary AP survey point to be undone");
  assert(collectorActivity.includes("清除本次橘色臨時點"), "collector must allow the active AP survey points to be cleared");
  assert(collectorActivity.includes("stepsSinceLastMeasurement < 3"), "collector must reject repeated AP survey points without detected movement");
  assert(collectorActivity.includes("deleteSurveyMeasurement(latest.id)"), "collector must delete the selected temporary AP survey point from Room");
  assert(collectorActivity.includes("refreshNearbyApCandidatePanel(result, results)"), "realtime positioning must refresh nearby AP survey candidates");
  assert(collectorActivity.includes("signalScore + distanceScore + fitScore + coverageScore"), "nearby AP candidates must combine current signal, distance, fit quality, and coverage");
  assert(layout.includes('android:id="@+id/layoutNearbyApCandidates"'), "collector must show nearby AP candidates after realtime positioning");
  assert(collectorActivity.includes('status = if (verified) "VERIFIED" else "CANDIDATE"'), "collector must gate verified AP status on survey quality");
  console.log("PASS: status/hours survive editing, coordinates preserved, keyword/notes ranking, recency bounds, progressive admin loading, category picker and syntax");
} finally {
  fs.rmSync(directory, { recursive: true, force: true });
}
